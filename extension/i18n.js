let current = 'en';

export function setLang(lang) {
  current = STRINGS[lang] ? lang : 'en';
  return current;
}

export function getLang() { return current; }

export function t(key, ...subs) {
  const s = (STRINGS[current] && STRINGS[current][key]) ?? STRINGS.en[key] ?? key;
  return s.replace(/\$(\d)/g, (_, n) => (subs[+n - 1] ?? ''));
}

// Strings the game-tab toast needs (bridge.js cannot import modules).
export function toastStrings(lang) {
  const pick = STRINGS[lang] || STRINGS.en;
  return { connected: pick.toastConnected, disconnected: pick.toastDisconnected, hubClosed: pick.toastHubClosed };
}

